"""从 src/core/model/shape.hpp 生成 Unity 示例用的形状名表。

共享内存只传 88 个 float + 88 个 valid 字节，没有名字；名字顺序就是契约。
手抄 88 项迟早漂移，所以和 v1 参数表一样用生成脚本。

用法：
    python tools/gen_unity_shape_names.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHAPE_HPP = ROOT / "src" / "core" / "model" / "shape.hpp"
OUT = ROOT / "sdk" / "samples" / "unity-face-gaze" / "Runtime" / "FaceGazeShapeNames.cs"


def load_names():
    text = SHAPE_HPP.read_text(encoding="utf-8")
    block = text.split("FGB_SHAPE_LIST", 1)
    if len(block) < 2:
        raise SystemExit("shape.hpp 里找不到 FGB_SHAPE_LIST")
    body = block[1].split("#define", 1)[0]
    names = re.findall(r"X\((\w+)\)", body)
    if len(names) != 88:
        raise SystemExit(f"形状数量是 {len(names)}，期望 88")
    if len(set(names)) != len(names):
        raise SystemExit("形状名有重复")
    return names


def main():
    names = load_names()
    lines = [
        "// <auto-generated>",
        "// 由 tools/gen_unity_shape_names.py 从 src/core/model/shape.hpp 生成，不要手改。",
        "// 顺序必须与 FgbSharedFrameV1.shapes / shape_valid 一致。",
        "// </auto-generated>",
        "namespace FaceGazeBridge",
        "{",
        "    public static class FaceGazeShapeNames",
        "    {",
        f"        public const int Count = {len(names)};",
        "",
    ]
    for index, name in enumerate(names):
        lines.append(f"        public const int {name} = {index};")
    lines += [
        "",
        "        public static readonly string[] Names =",
        "        {",
    ]
    for index, name in enumerate(names):
        comma = "," if index + 1 < len(names) else ""
        lines.append(f'            "{name}"{comma}')
    lines += [
        "        };",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}（{len(names)} 个形状）")


if __name__ == "__main__":
    main()
